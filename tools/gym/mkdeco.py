# python3 tools/gym/mkdeco.py <pokeemerald-expansion 폴더>
import sys, os, re
from PIL import Image, ImageDraw
PX = sys.argv[1]; OUT = 'gym/img/deco/'; BOUT = 'gym/img/badge/'
os.makedirs(OUT, exist_ok=True); os.makedirs(BOUT, exist_ok=True)
G = PX + '/graphics/object_events/'
def pal(n):
    L = [l for l in open(f'{G}palettes/npc_{n}.pal').read().split('\n')[3:] if l.strip()]
    return [tuple(int(v) for v in l.split()[:3]) for l in L]
P = {k: pal(k) for k in (1, 2, 3, 4)}
info = open(PX + '/src/data/object_events/object_event_graphics_info.h').read()
tag = {m.group(1): int(m.group(2)) for m in re.finditer(r'gObjectEventGraphicsInfo_(\w+) = \{\s*\.tileTag = \w+,\s*\.paletteTag = OBJ_EVENT_PAL_TAG_NPC_(\d)', info)}
camel = lambda s: ''.join(w.capitalize() for w in s.split('_'))
def conv(src, name, key):
    im = Image.open(src); px = im.load(); W, H = im.size; pl = P[tag.get(key, 1)]
    out = Image.new('RGBA', (W, H)); o = out.load()
    for y in range(H):
        for x in range(W):
            i = px[x, y]
            if i: o[x, y] = pl[i] + (255,)
    out.save(OUT + name + '.png', optimize=True)
n = 0
for d in ('dolls', 'cushions'):
    for f in sorted(os.listdir(G + 'pics/' + d)):
        b = f[:-4]
        if b.startswith('unused'): continue
        conv(f'{G}pics/{d}/{f}', b, camel(b)); n += 1
conv(G + 'pics/misc/statue.png', 'statue', 'Statue'); n += 1

