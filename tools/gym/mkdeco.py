    m = SH[TSH[t]]; c = TC[t]; im = Image.new('RGBA', (18, 18)); o = im.load()
    on = lambda x, y: 0 <= y < 16 and 0 <= x < 16 and m[y][x] == '#'
    for y in range(16):
        for x in range(16):
            if not on(x, y): continue
            edge = not (on(x - 1, y) and on(x + 1, y) and on(x, y - 1) and on(x, y + 1))
            k = .45 if edge else 1.25 if (x + y) < 12 and not on(x - 2, y - 2) else 1.1 if x + y < 14 else .82 if x + y > 20 else 1
            o[x + 1, y + 1] = shade(c, k)
